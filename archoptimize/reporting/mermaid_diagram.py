"""ComponentGraph → Mermaid flowchart text.

Generated by code, not by the LLM, so the same graph always gives the same diagram.
Mermaid renders in GitHub, Gradio Markdown and most docs tools.

Conventions in the picture:
- shape shows the component type (cylinder = database, stadium = users, ...)
- solid arrow = sync call, dotted arrow = async message
- red border = public (internet-facing)
"""

from __future__ import annotations

import re

from archoptimize.schemas.component_graph import ComponentGraph, ComponentType, EdgeMode

# (open, close) brackets for each component type's Mermaid shape.
_SHAPES: dict[ComponentType, tuple[str, str]] = {
    ComponentType.CLIENT: ("([", "])"),  # stadium
    ComponentType.DNS: ("((", "))"),  # circle
    ComponentType.CDN: ("((", "))"),
    ComponentType.WAF: ("{{", "}}"),  # hexagon
    ComponentType.LOAD_BALANCER: ("{{", "}}"),
    ComponentType.API_GATEWAY: ("{{", "}}"),
    ComponentType.RELATIONAL_DATABASE: ("[(", ")]"),  # cylinder
    ComponentType.NOSQL_DATABASE: ("[(", ")]"),
    ComponentType.CACHE: ("[(", ")]"),
    ComponentType.SEARCH: ("[(", ")]"),
    ComponentType.OBJECT_STORAGE: ("[(", ")]"),
    ComponentType.QUEUE: ("[/", "/]"),  # parallelogram
    ComponentType.STREAM: ("[/", "/]"),
    ComponentType.EXTERNAL_SERVICE: (">", "]"),  # flag
}
_DEFAULT_SHAPE = ("[", "]")  # rectangle

_UNSAFE_LABEL_CHARS = {'"': "#quot;", "<": "#lt;", ">": "#gt;"}


def _escape(text: str) -> str:
    for char, entity in _UNSAFE_LABEL_CHARS.items():
        text = text.replace(char, entity)
    return text.replace("\n", " ")


def _node_ids(graph: ComponentGraph) -> dict[str, str]:
    """Map component ids to safe Mermaid ids ('orders-db' -> 'n_orders_db').
    The 'n_' prefix avoids Mermaid keywords such as 'end'."""
    mapping: dict[str, str] = {}
    used: set[str] = set()
    for c in graph.components:
        base = "n_" + re.sub(r"[^a-zA-Z0-9_]", "_", c.id)
        node_id, n = base, 2
        while node_id in used:  # 'a-b' and 'a_b' would collide
            node_id, n = f"{base}_{n}", n + 1
        used.add(node_id)
        mapping[c.id] = node_id
    return mapping


def _label(graph: ComponentGraph, component_id: str) -> str:
    c = graph.component(component_id)
    lines = [f"<b>{_escape(c.name)}</b>"]
    details = [d for d in (c.aws_service, c.instance_type) if d]
    if details:
        lines.append(_escape(" · ".join(details)))
    if c.type is not ComponentType.CLIENT:
        scale = f"×{c.replicas}"
        if c.autoscaling:
            scale = f"×{c.autoscaling.min_replicas}–{c.autoscaling.max_replicas} (auto)"
        lines.append(f"{scale} · {c.availability_zones} AZ")
    return "<br/>".join(lines)


def to_mermaid(graph: ComponentGraph, direction: str = "LR") -> str:
    """Return Mermaid flowchart source for the graph (without ``` fences)."""
    if direction not in {"LR", "TB", "RL", "BT"}:
        raise ValueError(f"unsupported direction: {direction}")
    ids = _node_ids(graph)
    out = [f"flowchart {direction}"]

    for c in graph.components:
        open_, close = _SHAPES.get(c.type, _DEFAULT_SHAPE)
        out.append(f'    {ids[c.id]}{open_}"{_label(graph, c.id)}"{close}')

    for e in graph.edges:
        arrow = "-.->" if e.mode is EdgeMode.ASYNC else "-->"
        label = re.sub(r"[|\"<>]", "", e.protocol or "")
        middle = f"{arrow}|{label}|" if label else arrow
        out.append(f"    {ids[e.source]} {middle} {ids[e.target]}")

    public = [
        ids[c.id] for c in graph.components if c.public and c.type is not ComponentType.CLIENT
    ]
    if public:
        out.append("    classDef public stroke:#d33,stroke-width:2px")
        out.append(f"    class {','.join(public)} public")
    return "\n".join(out)


def to_mermaid_markdown(graph: ComponentGraph, direction: str = "LR") -> str:
    """Mermaid wrapped in a ```mermaid block, ready for Markdown (GitHub, Gradio)."""
    return f"```mermaid\n{to_mermaid(graph, direction)}\n```"
